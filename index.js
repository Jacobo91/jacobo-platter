class ProductGrid extends HTMLElement {
    constructor() {
        super();
        this.grid = this.querySelector('#product-grid');
        this.template = this.querySelector('#product-card-template');
        this.showMoreBtn = this.querySelector('#show-more-button');
        this.gridWrapper = this.querySelector('#product-grid-wrapper');

        this.isMobile = window.innerWidth < 496;
        this.showingAll = false;

        // bind handlers so we can add/remove them
        this._onResize = this._onResize.bind(this);
        this._onShowMoreClick = this._onShowMoreClick.bind(this);
    }

    connectedCallback() {
        this.renderProducts();

        // click handler
        if (this.showMoreBtn) {
            this.showMoreBtn.addEventListener("click", this._onShowMoreClick);
        }

        // resize handler to toggle mobile/desktop behavior
        window.addEventListener("resize", this._onResize);
    }

    disconnectedCallback() {
        if (this.showMoreBtn) {
            this.showMoreBtn.removeEventListener("click", this._onShowMoreClick);
        }
        window.removeEventListener("resize", this._onResize);
    }

    _onShowMoreClick() {
        const wasShowingAll = this.showingAll;
        this.showingAll = !this.showingAll;

        const startHeight = this.gridWrapper.scrollHeight;
        let endHeight;

        if (wasShowingAll) {
            // COLLAPSING (show less)
            const clone = this.gridWrapper.cloneNode(true);
            clone.style.position = "absolute";
            clone.style.visibility = "hidden";
            clone.style.pointerEvents = "none";
            clone.style.height = "auto";
            document.body.appendChild(clone);

            const originalGrid = clone.querySelector('#product-grid');
            originalGrid.innerHTML = "";
            let collapsedProducts = products.slice(0, 4);
            collapsedProducts.forEach(product => {
                originalGrid.appendChild(this.createProductCard(product));
            });

            endHeight = clone.scrollHeight;
            document.body.removeChild(clone);

            this.gridWrapper.style.height = `${startHeight}px`;
            this.gridWrapper.offsetHeight;
            this.gridWrapper.style.transition = "height 0.6s ease";
            this.gridWrapper.style.height = `${endHeight}px`;

            this.gridWrapper.addEventListener("transitionend", () => {
                this.renderProducts();
                this.gridWrapper.style.height = "auto";
            }, { once: true });

            this.smoothScrollTo(this.gridWrapper.offsetTop - 80, 900);
        } else {
            // EXPANDING (show more)
            this.renderProducts();

            requestAnimationFrame(() => {
                endHeight = this.gridWrapper.scrollHeight;
                this.gridWrapper.style.height = `${startHeight}px`;
                this.gridWrapper.offsetHeight;
                this.gridWrapper.style.transition = "height 0.6s ease";
                this.gridWrapper.style.height = `${endHeight}px`;

                this.gridWrapper.addEventListener("transitionend", () => {
                    this.gridWrapper.style.height = "auto";
                }, { once: true });
            });
        }
    }

    _onResize() {
        const prevIsMobile = this.isMobile;
        this.isMobile = window.innerWidth < 496;

        // if we moved from mobile -> desktop: show everything
        if (prevIsMobile && !this.isMobile) {
            this.showingAll = true;
        }

        // if we moved from desktop -> mobile: collapse and reset
        if (!prevIsMobile && this.isMobile) {
            this.showingAll = false;
        }

        // show/hide the button depending on mobile state
        if (this.showMoreBtn) {
            this.showMoreBtn.style.display = this.isMobile ? "" : "none";
        }

        // re-render to apply changes
        this.renderProducts();
    }

    createProductCard(product) {
        const productCard = document.createElement('div');
        productCard.setAttribute('id', 'product-card');

        const card = this.template.content.cloneNode(true);
        const featuredImage = card.querySelector('#featured-image');
        const tagsContainer = card.querySelector('#tags-container');
        const tags = product.tags || [];

        tags.forEach(tag => {
            const span = document.createElement('span');
            span.textContent = tag;
            span.classList.add(
                'text-[8px]', 
                'md:text-[10px]', 
                tag === 'bestseller' ? 'bg-[#FFFFFF]' : 'bg-[#5C7962]',
                'py-[4px]', 
                'px-[8px]', 
                'rounded-full', 
                'border-black',
                'border-[1px]',
                'border-[solid]',
                'uppercase',
                tag === 'bestseller' ? 'text-[#000000]' : 'text-[#FFFFFF]',
                'tracking-[0.32px]'
            );
            tagsContainer.appendChild(span);
        });

        const link = card.querySelector('a');
        if (link) link.href = product.url || '#';
        if (featuredImage) featuredImage.src = product['featured-image'];

        if (featuredImage) {
            featuredImage.addEventListener('mouseover', () => {
                if (product.images?.[1]) featuredImage.src = product.images[1];
            });

            featuredImage.addEventListener('mouseout', () => {
                featuredImage.src = product['featured-image'];
            });
        }

        const titleEl = card.querySelector('#product-title');
        if (titleEl) titleEl.textContent = product.title;

        const priceEl = card.querySelector('#product-price');
        if (priceEl) priceEl.textContent = `$${product.price}`;

        productCard.appendChild(card);
        return productCard;
    }

    renderProducts() {
        this.grid.innerHTML = "";

        // when desktop, always show all products
        let productsToRender = (!this.isMobile) ? products : (this.showingAll ? products : products.slice(0, 4));

        // update button text and visibility
        if (this.showMoreBtn) {
            if (!this.isMobile) {
                this.showMoreBtn.style.display = "none";
            } else {
                this.showMoreBtn.style.display = "";
                this.showMoreBtn.textContent = this.showingAll ? 'Show Less' : 'Show More';
            }
        }

        productsToRender.forEach(product => {
            this.grid.appendChild(this.createProductCard(product));
        });
    }

    smoothScrollTo(targetY, duration = 1000) {
        const startY = window.scrollY;
        const distance = targetY - startY;
        const startTime = performance.now();

        const step = (currentTime) => {
            const elapsed = currentTime - startTime;
            const progress = Math.min(elapsed / duration, 1);
            const ease = 1 - Math.pow(1 - progress, 3); // cubic ease-out
            window.scrollTo(0, startY + distance * ease);
            if (progress < 1) requestAnimationFrame(step);
        };

        requestAnimationFrame(step);
    }
}

customElements.define("product-grid", ProductGrid);
